CREATE TABLE clientes (
    id_cliente          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tipo_identificacion VARCHAR2(3)   DEFAULT 'NIT' NOT NULL,
    identificacion      VARCHAR2(20)  NOT NULL,
    nombre              VARCHAR2(100) NOT NULL,
    telefono            VARCHAR2(15),
    correo              VARCHAR2(100),
    puntos              NUMBER(10)    DEFAULT 0 NOT NULL,
    activo              CHAR(1)       DEFAULT 'S' NOT NULL,
    fecha_registro      DATE          DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT pk_clientes PRIMARY KEY (id_cliente),
    CONSTRAINT uq_clientes_identificacion UNIQUE (identificacion),
    CONSTRAINT ck_clientes_tipo_id CHECK (tipo_identificacion IN ('NIT', 'DPI')),
    CONSTRAINT ck_clientes_puntos CHECK (puntos >= 0),
    CONSTRAINT ck_clientes_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE productos (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo      VARCHAR2(10)  NOT NULL,
    nombre      VARCHAR2(100) NOT NULL,
    categoria   VARCHAR2(15)  NOT NULL,
    precio      NUMBER(10,2)  NOT NULL,
    existencia  NUMBER(10)    DEFAULT 0 NOT NULL,
    activo      CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (id_producto),
    CONSTRAINT uq_productos_codigo UNIQUE (codigo),
    CONSTRAINT ck_productos_categoria CHECK (categoria IN ('SANDWICH', 'BEBIDA', 'ACOMPANAMIENTO')),
    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_existencia CHECK (existencia >= 0),
    CONSTRAINT ck_productos_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE menus (
    id_menu           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo            VARCHAR2(10)  NOT NULL,
    nombre            VARCHAR2(100) NOT NULL,
    precio            NUMBER(10,2)  NOT NULL,
    id_sandwich       NUMBER        NOT NULL,
    id_bebida         NUMBER        NOT NULL,
    id_acompanamiento NUMBER        NOT NULL,
    activo            CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_menus PRIMARY KEY (id_menu),
    CONSTRAINT uq_menus_codigo UNIQUE (codigo),
    CONSTRAINT fk_menus_sandwich FOREIGN KEY (id_sandwich) REFERENCES productos (id_producto),
    CONSTRAINT fk_menus_bebida FOREIGN KEY (id_bebida) REFERENCES productos (id_producto),
    CONSTRAINT fk_menus_acompanamiento FOREIGN KEY (id_acompanamiento) REFERENCES productos (id_producto),
    CONSTRAINT ck_menus_precio CHECK (precio >= 0),
    CONSTRAINT ck_menus_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE pedidos (
    id_pedido  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente NUMBER       NOT NULL,
    fecha      DATE         DEFAULT CURRENT_DATE NOT NULL,
    estado     VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    total      NUMBER(10,2) DEFAULT 0 NOT NULL,
    puntos     NUMBER(10)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_pedidos PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN ('PENDIENTE', 'PAGADO', 'ENTREGADO', 'ANULADO')),
    CONSTRAINT ck_pedidos_total CHECK (total >= 0),
    CONSTRAINT ck_pedidos_puntos CHECK (puntos >= 0)
);

CREATE TABLE detalle_pedido (
    id_detalle      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido       NUMBER       NOT NULL,
    tipo_item       VARCHAR2(10) NOT NULL,
    id_producto     NUMBER,
    id_menu         NUMBER,
    cantidad        NUMBER(10)   NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal        NUMBER(10,2) NOT NULL,
    puntos          NUMBER(10)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_detalle_pedido PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos (id_pedido),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
    CONSTRAINT fk_detalle_menu FOREIGN KEY (id_menu) REFERENCES menus (id_menu),
    CONSTRAINT ck_detalle_tipo CHECK (
        (tipo_item = 'PRODUCTO' AND id_producto IS NOT NULL AND id_menu IS NULL)
        OR (tipo_item = 'MENU' AND id_menu IS NOT NULL AND id_producto IS NULL)),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0),
    CONSTRAINT ck_detalle_subtotal CHECK (subtotal >= 0),
    CONSTRAINT ck_detalle_puntos CHECK (puntos >= 0)
);

CREATE TABLE pagos (
    id_pago        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido      NUMBER       NOT NULL,
    metodo         VARCHAR2(10) NOT NULL,
    estado         VARCHAR2(10) NOT NULL,
    monto          NUMBER(10,2) NOT NULL,
    monto_recibido NUMBER(10,2),
    cambio         NUMBER(10,2),
    referencia     VARCHAR2(30),
    fecha          DATE         DEFAULT CURRENT_DATE NOT NULL,
    CONSTRAINT pk_pagos PRIMARY KEY (id_pago),
    CONSTRAINT fk_pagos_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos (id_pedido),
    CONSTRAINT ck_pagos_metodo CHECK (metodo IN ('EFECTIVO', 'TARJETA')),
    CONSTRAINT ck_pagos_estado CHECK (estado IN ('APROBADO', 'RECHAZADO')),
    CONSTRAINT ck_pagos_monto CHECK (monto >= 0),
    CONSTRAINT ck_pagos_datos CHECK (
        (metodo = 'EFECTIVO' AND monto_recibido IS NOT NULL)
        OR (metodo = 'TARJETA' AND referencia IS NOT NULL))
);

CREATE UNIQUE INDEX uq_pagos_aprobado ON pagos (CASE WHEN estado = 'APROBADO' THEN id_pedido END);

CREATE TABLE movimientos_inventario (
    id_movimiento       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto         NUMBER       NOT NULL,
    fecha               DATE         DEFAULT CURRENT_DATE NOT NULL,
    tipo                VARCHAR2(15) NOT NULL,
    cantidad            NUMBER(10)   NOT NULL,
    existencia_anterior NUMBER(10)   NOT NULL,
    existencia_nueva    NUMBER(10)   NOT NULL,
    referencia          VARCHAR2(50),
    CONSTRAINT pk_movimientos_inventario PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_inv_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
    CONSTRAINT ck_mov_inv_tipo CHECK (tipo IN ('ABASTECIMIENTO', 'VENTA', 'CANJE')),
    CONSTRAINT ck_mov_inv_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_mov_inv_existencias CHECK (existencia_anterior >= 0 AND existencia_nueva >= 0)
);

CREATE TABLE recompensas (
    id_recompensa     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(100) NOT NULL,
    puntos_necesarios NUMBER(10)    NOT NULL,
    tipo              VARCHAR2(10)  NOT NULL,
    id_producto       NUMBER,
    id_menu           NUMBER,
    activo            CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_recompensas PRIMARY KEY (id_recompensa),
    CONSTRAINT fk_recompensas_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto),
    CONSTRAINT fk_recompensas_menu FOREIGN KEY (id_menu) REFERENCES menus (id_menu),
    CONSTRAINT ck_recompensas_puntos CHECK (puntos_necesarios > 0),
    CONSTRAINT ck_recompensas_tipo CHECK (
        (tipo = 'PRODUCTO' AND id_producto IS NOT NULL AND id_menu IS NULL)
        OR (tipo = 'MENU' AND id_menu IS NOT NULL AND id_producto IS NULL)),
    CONSTRAINT ck_recompensas_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE canjes (
    id_canje      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    NUMBER     NOT NULL,
    id_recompensa NUMBER     NOT NULL,
    fecha         DATE       DEFAULT CURRENT_DATE NOT NULL,
    puntos_usados NUMBER(10) NOT NULL,
    CONSTRAINT pk_canjes PRIMARY KEY (id_canje),
    CONSTRAINT fk_canjes_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente),
    CONSTRAINT fk_canjes_recompensa FOREIGN KEY (id_recompensa) REFERENCES recompensas (id_recompensa),
    CONSTRAINT ck_canjes_puntos CHECK (puntos_usados > 0)
);

CREATE TABLE movimientos_puntos (
    id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    NUMBER       NOT NULL,
    fecha         DATE         DEFAULT CURRENT_DATE NOT NULL,
    tipo          VARCHAR2(12) NOT NULL,
    puntos        NUMBER(10)   NOT NULL,
    id_pedido     NUMBER,
    id_canje      NUMBER,
    CONSTRAINT pk_movimientos_puntos PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_pts_cliente FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente),
    CONSTRAINT fk_mov_pts_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos (id_pedido),
    CONSTRAINT fk_mov_pts_canje FOREIGN KEY (id_canje) REFERENCES canjes (id_canje),
    CONSTRAINT ck_mov_pts_tipo CHECK (
        (tipo = 'ACUMULACION' AND puntos > 0 AND id_pedido IS NOT NULL AND id_canje IS NULL)
        OR (tipo = 'CANJE' AND puntos < 0 AND id_canje IS NOT NULL AND id_pedido IS NULL))
);
